SELECT
    TRIM(DEVICEID) AS DEVICE_ID,

    LATITUDE,

    LONGITUDE,

    ST_MAKEPOINT(LONGITUDE, LATITUDE) AS GEO_LOCATION,

    TRY_TO_TIMESTAMP_NTZ(
        TRIM(TIMESTAMP),
        'YYYY-MM-DD HH24:MI:SS.FF9'
    ) AS EVENT_TIMESTAMP

FROM {{ source('geopulse', 'gps_pings') }}

WHERE TRIM(DEVICEID) IS NOT NULL
  AND TRIM(DEVICEID) != ''
  AND LATITUDE BETWEEN 11.00 AND 11.10
  AND LONGITUDE BETWEEN 76.90 AND 77.10
  AND TRY_TO_TIMESTAMP_NTZ(
        TRIM(TIMESTAMP),
        'YYYY-MM-DD HH24:MI:SS.FF9'
      ) IS NOT NULL
