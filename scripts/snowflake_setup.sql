-- GeoPulse Snowflake Database Setup

CREATE DATABASE IF NOT EXISTS GEOPULSE;

CREATE SCHEMA IF NOT EXISTS GEOPULSE.RAW;

CREATE TABLE IF NOT EXISTS GEOPULSE.RAW.MOBILE_GPS_PINGS (
    DEVICE_ID VARCHAR,
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    TIMESTAMP TIMESTAMP_NTZ,
    LOCATION GEOGRAPHY
);

-- Populate GEOGRAPHY from longitude and latitude
UPDATE GEOPULSE.RAW.MOBILE_GPS_PINGS
SET LOCATION = ST_MAKEPOINT(LONGITUDE, LATITUDE);

-- Create store reference table
CREATE TABLE IF NOT EXISTS GEOPULSE.RAW.STORES (
    STORE_ID VARCHAR,
    STORE_NAME VARCHAR,
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    LOCATION GEOGRAPHY
);

-- Populate store GEOGRAPHY from longitude and latitude
UPDATE GEOPULSE.RAW.STORES
SET LOCATION = ST_MAKEPOINT(LONGITUDE, LATITUDE);

-- Create 500-meter store catchment table
CREATE TABLE IF NOT EXISTS GEOPULSE.RAW.STORE_CATCHMENTS (
    STORE_ID VARCHAR,
    STORE_NAME VARCHAR,
    CATCHMENT_AREA GEOMETRY
);

-- Generate and store 500-meter catchment polygons
INSERT INTO GEOPULSE.RAW.STORE_CATCHMENTS (
    STORE_ID,
    STORE_NAME,
    CATCHMENT_AREA
)
SELECT
    STORE_ID,
    STORE_NAME,
    ST_BUFFER(
        ST_TRANSFORM(
            TO_GEOMETRY(ST_ASWKT(LOCATION)),
            4326,
            32643
        ),
        500
    )
FROM GEOPULSE.RAW.STORES;