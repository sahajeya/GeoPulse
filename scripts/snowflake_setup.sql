-- GeoPulse Snowflake Database Setup

CREATE DATABASE IF NOT EXISTS GEOPULSE;

CREATE SCHEMA IF NOT EXISTS GEOPULSE.RAW;

CREATE TABLE IF NOT EXISTS GEOPULSE.RAW.MOBILE_GPS_PINGS (
    DEVICE_ID VARCHAR,
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    TIMESTAMP TIMESTAMP_NTZ,
    LOCATION GEOGRAPHY
);

-- Populate GEOGRAPHY from longitude and latitude
UPDATE GEOPULSE.RAW.MOBILE_GPS_PINGS
SET LOCATION = ST_MAKEPOINT(LONGITUDE, LATITUDE);

-- Create store reference table
CREATE TABLE IF NOT EXISTS GEOPULSE.RAW.STORES (
    STORE_ID VARCHAR,
    STORE_NAME VARCHAR,
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    LOCATION GEOGRAPHY
);

-- Populate store GEOGRAPHY from longitude and latitude
UPDATE GEOPULSE.RAW.STORES
SET LOCATION = ST_MAKEPOINT(LONGITUDE, LATITUDE);

-- Create 500-meter store catchment table
CREATE TABLE IF NOT EXISTS GEOPULSE.RAW.STORE_CATCHMENTS (
    STORE_ID VARCHAR,
    STORE_NAME VARCHAR,
    CATCHMENT_AREA GEOMETRY
);

-- Generate and store 500-meter catchment polygons
INSERT INTO GEOPULSE.RAW.STORE_CATCHMENTS (
    STORE_ID,
    STORE_NAME,
    CATCHMENT_AREA
)
SELECT
    STORE_ID,
    STORE_NAME,
    ST_BUFFER(
        ST_TRANSFORM(
            TO_GEOMETRY(ST_ASWKT(LOCATION)),
            4326,
            32643
        ),
        500
    )
FROM GEOPULSE.RAW.STORES;

-- Create GPS-to-store spatial join table
CREATE TABLE IF NOT EXISTS GEOPULSE.RAW.GPS_STORE_CATCHMENTS (
    DEVICE_ID VARCHAR,
    TIMESTAMP TIMESTAMP_NTZ,
    STORE_ID VARCHAR,
    STORE_NAME VARCHAR
);

-- Assign GPS pings to 500-meter store catchments
INSERT INTO GEOPULSE.RAW.GPS_STORE_CATCHMENTS (
    DEVICE_ID,
    TIMESTAMP,
    STORE_ID,
    STORE_NAME
)
SELECT
    g.DEVICE_ID,
    g.TIMESTAMP,
    s.STORE_ID,
    s.STORE_NAME
FROM GEOPULSE.RAW.MOBILE_GPS_PINGS g
JOIN GEOPULSE.RAW.STORE_CATCHMENTS s
    ON ST_WITHIN(
        ST_TRANSFORM(
            ST_GEOMETRYFROMWKT(ST_ASWKT(g.LOCATION), 4326),
            4326,
            32643
        ),
        s.CATCHMENT_AREA
    );

-- Create hourly footfall table
CREATE TABLE IF NOT EXISTS GEOPULSE.RAW.HOURLY_FOOTFALL (
    STORE_ID VARCHAR,
    STORE_NAME VARCHAR,
    FOOTFALL_DATE DATE,
    HOUR_OF_DAY NUMBER,
    UNIQUE_VISITORS NUMBER,
    TOTAL_PINGS NUMBER
);

-- Aggregate hourly footfall
INSERT INTO GEOPULSE.RAW.HOURLY_FOOTFALL (
    STORE_ID,
    STORE_NAME,
    FOOTFALL_DATE,
    HOUR_OF_DAY,
    UNIQUE_VISITORS,
    TOTAL_PINGS
)
SELECT
    STORE_ID,
    STORE_NAME,
    CAST(TIMESTAMP AS DATE),
    EXTRACT(HOUR FROM TIMESTAMP),
    COUNT(DISTINCT DEVICE_ID),
    COUNT(*)
FROM GEOPULSE.RAW.GPS_STORE_CATCHMENTS
GROUP BY
    STORE_ID,
    STORE_NAME,
    CAST(TIMESTAMP AS DATE),
    EXTRACT(HOUR FROM TIMESTAMP);