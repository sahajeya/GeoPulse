SELECT
    STORE_ID,
    STORE_NAME,
    SUM(UNIQUE_VISITORS) AS TOTAL_UNIQUE_VISITOR_COUNTS,
    SUM(TOTAL_PINGS) AS TOTAL_PINGS,
    COUNT(*) AS TOTAL_HOURLY_RECORDS,
    AVG(UNIQUE_VISITORS) AS AVG_HOURLY_VISITORS
FROM {{ ref('stg_hourly_footfall') }}
GROUP BY
    STORE_ID,
    STORE_NAME
ORDER BY
    STORE_ID